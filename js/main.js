function layDanhSachPhong() {
    var duLieu = localStorage.getItem("dsPhong");
    if (!duLieu) {
        localStorage.setItem("dsPhong", JSON.stringify(dsMoiDau));
        return dsMoiDau;
    }
    return JSON.parse(duLieu);
}

function hienThiPhongTrangChu() {
    var container = document.getElementById("roomGridContainer");
    if (!container) return;

    var searchKeyword = document.getElementById("searchRoom") ? document.getElementById("searchRoom").value.toLowerCase() : "";
    var filterType = document.getElementById("filterType") ? document.getElementById("filterType").value : "All";
    var filterPrice = document.getElementById("filterPrice") ? document.getElementById("filterPrice").value : "All";
    var filterStatus = document.getElementById("filterStatus") ? document.getElementById("filterStatus").value : "All";

    var ds = layDanhSachPhong();
    container.innerHTML = "";

    for (var i = 0; i < ds.length; i++) {
        var matchSearch = ds[i].ten.toLowerCase().includes(searchKeyword);
        var matchType = (filterType === "All") || ds[i].ten.toLowerCase().includes(filterType.toLowerCase());
        
        var giaNum = Number(ds[i].gia);
        var matchPrice = true;
        if (filterPrice === "1") matchPrice = (giaNum < 700000);
        else if (filterPrice === "2") matchPrice = (giaNum >= 700000 && giaNum <= 1000000);
        else if (filterPrice === "3") matchPrice = (giaNum > 1000000);

        var matchStatus = (filterStatus === "All") || (ds[i].trangThai === filterStatus);

        if (matchSearch && matchType && matchPrice && matchStatus) {
            var imgUrl = ds[i].hinhAnh || "https://images.unsplash.com/photo-1566073771259-6a8506099945?auto=format&fit=crop&w=600&q=80";
            var card = document.createElement("div");
            card.className = "room-card";
            card.innerHTML = `
                <img src="${imgUrl}" alt="${ds[i].ten}" style="width:100%; height:160px; object-fit:cover; border-radius:6px; margin-bottom:10px;">
                <h3>${ds[i].ten}</h3>
                <p>Giá: ${Number(ds[i].gia).toLocaleString('vi-VN')} VNĐ</p>
                <p>Trạng thái: <span style="color: ${ds[i].trangThai === 'Còn trống' ? 'green' : 'red'};">${ds[i].trangThai}</span></p>
            `;
            
            (function(phongItem) {
                card.onclick = function() {
                    var modal = document.getElementById("roomModal");
                    if (!modal) return;

                    var giaDinhDang = Number(phongItem.gia).toLocaleString('vi-VN');
                    document.getElementById("modalImg").src = phongItem.hinhAnh || imgUrl;
                    document.getElementById("modalName").innerText = phongItem.ten;
                    document.getElementById("modalPrice").innerText = giaDinhDang + " VNĐ / đêm";
                    document.getElementById("modalStatus").innerText = phongItem.trangThai;
                    document.getElementById("modalStatus").style.color = (phongItem.trangThai === 'Còn trống' ? 'green' : 'red');
                    document.getElementById("modalAmenities").innerText = phongItem.tienIch;

                    var btnContainer = document.getElementById("modalActionBtn");
                    if (phongItem.trangThai === 'Còn trống') {
                        btnContainer.innerHTML = `<a href="booking.html" class="btn-submit" style="text-align: center; text-decoration: none; display: block;">Đặt Ngay</a>`;
                    } else {
                        btnContainer.innerHTML = `<button class="btn-submit" style="background:#cbd5e1; cursor:not-allowed; width: 100%;" disabled>Phòng Đã Được Đặt</button>`;
                    }

                    modal.style.display = "flex";
                };
            })(ds[i]);

            container.appendChild(card);
        }
    }
}

function dongModal() {
    var modal = document.getElementById("roomModal");
    if (modal) modal.style.display = "none";
}

function hienThiOptionDatPhong() {
    var selectBox = document.getElementById("loaiPhong");
    if (!selectBox) return;

    var ds = layDanhSachPhong();
    selectBox.innerHTML = "";

    var count = 0;
    for (var i = 0; i < ds.length; i++) {
        if (ds[i].trangThai === "Còn trống") {
            var giaDinhDang = Number(ds[i].gia).toLocaleString('vi-VN');
            var option = `<option value="${ds[i].ten}">${ds[i].ten} - ${giaDinhDang} VNĐ / đêm</option>`;
            selectBox.innerHTML += option;
            count++;
        }
    }

    if (count === 0) {
        selectBox.innerHTML = `<option value="">Hết phòng trống</option>`;
    }

    if (typeof capNhatPreviewPhong === "function") {
        capNhatPreviewPhong();
    }
}